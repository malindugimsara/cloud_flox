    <!-- Interactive Pricing Switcher & Sticky Header Tracker Script -->
    <script>
    (function () {
        const btnMonthly = document.getElementById('btnMonthly');
        const btnYearly = document.getElementById('btnYearly');
        if (!btnMonthly || !btnYearly) return;

        const priceVals = document.querySelectorAll('.price-val');
        const billingNotes = document.querySelectorAll('.billing-note');
        const ctaButtons = document.querySelectorAll('[data-pid]');

        function setBillingCycle(isYearly) {
            if (isYearly) {
                btnYearly.classList.add('active');
                btnMonthly.classList.remove('active');
            } else {
                btnMonthly.classList.add('active');
                btnYearly.classList.remove('active');
            }

            priceVals.forEach(el => {
                const val = isYearly ? el.getAttribute('data-yearly') : el.getAttribute('data-monthly');
                if (val) {
                    el.style.opacity = '0';
                    setTimeout(() => {
                        el.textContent = val;
                        el.style.opacity = '1';
                    }, 120);
                }
            });

            billingNotes.forEach(el => {
                const note = isYearly ? el.getAttribute('data-yearly') : el.getAttribute('data-monthly');
                if (note) {
                    el.textContent = note;
                }
            });

            // Update WHMCS billing cycle parameter in links
            const cycleParam = isYearly ? 'annually' : 'monthly';
            ctaButtons.forEach(btn => {
                const pid = btn.getAttribute('data-pid');
                if (pid) {
                    btn.href = `https://my.cloudflox.com/cart.php?a=add&pid=${pid}&billingcycle=${cycleParam}`;
                }
            });
        }

        btnMonthly.addEventListener('click', () => setBillingCycle(false));
        btnYearly.addEventListener('click', () => setBillingCycle(true));

        // Dynamic Sticky Table Header Offset Tracker
        function updateStickyTableHeader() {
            const header = document.querySelector('.cf-header-wrapper');
            if (header) {
                const rect = header.getBoundingClientRect();
                const offset = Math.max(0, Math.round(rect.bottom));
                document.documentElement.style.setProperty('--cf-header-h', offset + 'px');
            }
        }
        window.addEventListener('scroll', updateStickyTableHeader, { passive: true });
        window.addEventListener('resize', updateStickyTableHeader, { passive: true });
        updateStickyTableHeader();
    })();
    </script>
